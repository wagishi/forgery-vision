"""
Image Tampering Detection API
------------------------------
POST /predict   - upload an image, get back a tampering verdict + evidence
GET  /health    - liveness check
GET  /docs      - interactive Swagger UI (auto-generated by FastAPI)

Run locally:
    uvicorn main:app --reload --port 8000
"""

from fastapi import FastAPI, File, UploadFile, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import JSONResponse

from model.tamper_detect import analyze_image

app = FastAPI(
    title="Image Tampering Detection API",
    description="Forensic image analysis using Error Level Analysis (ELA), "
                "noise-inconsistency, and edge-artifact detection to flag "
                "digitally manipulated images.",
    version="1.0.0",
)

# Allow the demo frontend (or any frontend, for assessment purposes) to call this API.
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_methods=["*"],
    allow_headers=["*"],
)

ALLOWED_CONTENT_TYPES = {"image/jpeg", "image/jpg", "image/png", "image/webp"}


@app.get("/health")
def health():
    return {"status": "ok"}


@app.get("/")
def root():
    return {"message": "Image Tampering Detection API is running"}


@app.post("/predict")
async def predict(file: UploadFile = File(...)):
    if file.content_type not in ALLOWED_CONTENT_TYPES:
        raise HTTPException(
            status_code=400,
            detail=f"Unsupported file type '{file.content_type}'. "
                   f"Upload a JPEG, PNG, or WEBP image.",
        )

    image_bytes = await file.read()
    if not image_bytes:
        raise HTTPException(status_code=400, detail="Empty file upload.")

    try:
        result = analyze_image(image_bytes)
    except Exception as exc:
        raise HTTPException(status_code=422, detail=f"Could not process image: {exc}")

    return JSONResponse({
        "prediction": result.label,
        "confidence": result.confidence,
        "evidence": {
            "ela_hot_region_pct": result.hot_region_pct,
            "noise_inconsistency_score": result.noise_score,
            "edge_artifact_score": result.edge_score,
        },
        "ela_visualization_png_base64": result.ela_image_b64,
    })


if __name__ == "__main__":
    import uvicorn
    uvicorn.run("main:app", host="0.0.0.0", port=8000, reload=True)
